// Packs textures/<layer>.png|jpg into textures/_pack.js as data URLs (so they load from file://).
// Run: node pack-textures.mjs
import { readdirSync, readFileSync, writeFileSync } from 'fs';
const dir = 'textures';
const files = readdirSync(dir).filter((f) => /\.(png|jpe?g)$/i.test(f));
let out = `// Generated by pack-textures.mjs — ${files.length} texture(s)\nwindow.MAPGEN_TEXTURES = window.MAPGEN_TEXTURES || {};\n`;
for (const f of files) {
  const name = f.replace(/\.(png|jpe?g)$/i, '');
  const mime = /png$/i.test(f) ? 'image/png' : 'image/jpeg';
  out += `MAPGEN_TEXTURES[${JSON.stringify(name)}] = "data:${mime};base64,${readFileSync(`${dir}/${f}`).toString('base64')}";\n`;
}
writeFileSync(`${dir}/_pack.js`, out);
console.log('packed', files.map((f) => f.replace(/\.\w+$/, '')).join(', ') || '(none)');

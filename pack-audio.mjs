// Sound list: scans assets/audio/ambience and writes src/audio-list.js (the page opens from disk and can't list
// folders itself). It also renders a muffled copy of each ground and shout track into assets/audio/_far/ for
// "heard from a distance" (a page opened from disk can't filter audio live). Needs ffmpeg.
// Run: node pack-audio.mjs [--no-far]
import { readdirSync, statSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { join, relative, basename } from 'path';
import { execFileSync } from 'child_process';

const ROOT = 'assets/audio/ambience', FAR = 'assets/audio/_far';
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : /\.(mp3|ogg|wav|m4a)$/i.test(f) ? [p] : []; });
const files = existsSync(ROOT) ? walk(ROOT).sort() : [];
const ROT = 'assets/audio/rotating camera', rotFiles = existsSync(ROT) ? walk(ROT).sort() : [];
const dur = (f) => { try { return parseFloat(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString()) || 0; } catch { return 0; } };
const out = { general: [], night: [], ground: [], shouts: [], wind: [], fly: [], rainGround: [], rainSky: [], rainClose: [], rotBed: [], rotHit: [], dogs: [], animals: [], birds: [], steps: {} };
for (const f of files) {
  const r = relative(ROOT, f).toLowerCase(), n = basename(f).toLowerCase(), url = f.replace(/\\/g, '/');
  if (r.startsWith('general/')) (n.includes('night') ? out.night : out.general).push(url);
  else if (r.startsWith('ground level/')) (r.includes('market shouts/') || n.includes('aguas frescas') ? out.shouts : out.ground).push(url);
  else if (r.startsWith('rain/')) (n.includes('sky') ? out.rainSky : n.includes('close') ? out.rainClose : out.rainGround).push(url);
  else if (r.startsWith('dogs/')) out.dogs.push(url);
  else if (r.startsWith('animals/')) out.animals.push(url);
  else if (r.startsWith('birds/') || r.startsWith('brids/')) out.birds.push(url);
  else if (r.startsWith('strong wind/')) (n.includes('flying') ? out.fly : out.wind).push(url);
}
// rotating the camera: the long ones loop under a fast spin, the short ones are whooshes as it starts
for (const f of rotFiles) (dur(f) >= 12 ? out.rotBed : out.rotHit).push(f.replace(/\\/g, '/'));
// footsteps: single steps cut by cut-steps.py, named <surface>_<walk|run|land>_….mp3
const STEPS = 'assets/audio/_footsteps_cut';
if (existsSync(STEPS)) for (const f of readdirSync(STEPS).filter((f) => /\.mp3$/i.test(f)).sort()) { const [surf, act] = f.split('_'); ((out.steps[surf] ||= {})[act] ||= []).push(`${STEPS}/${f}`); }
const farOf = (u) => `${FAR}/${u.slice(ROOT.length + 1).replace(/[\/\\]/g, '__')}`;
const far = {};
if (!process.argv.includes('--no-far')) {
  mkdirSync(FAR, { recursive: true });
  for (const u of [...out.ground, ...out.shouts, ...out.dogs, ...out.animals]) {
    const o = farOf(u).replace(/\.\w+$/, '.mp3'); far[u] = o;
    if (existsSync(o)) continue;
    execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', u, '-af', 'lowpass=f=650,lowpass=f=650,highpass=f=70,volume=0.85', '-ac', '1', '-b:a', '80k', o]);
    console.log('far', o);
  }
} else for (const u of [...out.ground, ...out.shouts, ...out.dogs, ...out.animals]) { const o = farOf(u).replace(/\.\w+$/, '.mp3'); if (existsSync(o)) far[u] = o; }
writeFileSync('src/audio-list.js', `// generated by pack-audio.mjs — do not edit\nexport const AUDIO = ${JSON.stringify(out, null, 1)};\nexport const FAR = ${JSON.stringify(far, null, 1)};\n`);
console.log(Object.entries(out).map(([k, v]) => `${k} ${v.length}`).join(' · '), `· far ${Object.keys(far).length}`);

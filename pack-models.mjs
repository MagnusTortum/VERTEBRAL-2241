// Packs models/<name>.glb into models/_pack.js as base64 (so they load from file://).
// Run: node pack-models.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'fs';
const dir = 'models';
const files = existsSync(dir) ? readdirSync(dir).filter((f) => /\.glb$/i.test(f)) : [];
let out = `// Generated by pack-models.mjs — ${files.length} model(s)\nwindow.MAPGEN_MODELS = window.MAPGEN_MODELS || {};\n`;
for (const f of files) out += `MAPGEN_MODELS[${JSON.stringify(f.replace(/\.glb$/i, ''))}] = "${readFileSync(`${dir}/${f}`).toString('base64')}";\n`;
writeFileSync(`${dir}/_pack.js`, out);
console.log('packed', files.length, 'models');
